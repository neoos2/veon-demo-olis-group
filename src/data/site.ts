// Image helper data (generated by scripts/images.mjs).
type ImgMap = Record<string, [number, number, number]>;
const IMG = images as ImgMap;
export function srcset(name: string, widths: number[]): string {
  return widths.map((w) => `img/${name}-${w}.webp ${IMG[`${name}-${w}`][0]}w`).join(", ");
}
export function size(name: string, w: number): { width: number; height: number; src: string } {
  const [width, height] = IMG[`${name}-${w}`];
  return { width, height, src: `img/${name}-${w}.webp` };
}

